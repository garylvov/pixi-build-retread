/// Load every `<project>.toml` under `<pack>/<records_dir>/`, sorted by
/// project so a run's log order is stable.
pub fn load_records(pack_dir: &Path, records_dir: &str) -> Result<Vec<PathSourceRecord>> {
    let dir = pack_dir.join(records_dir);
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut out = Vec::new();
    for entry in
        std::fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))?
    {
        let entry = entry?;
        let file = entry.path();
        if file.extension().and_then(|e| e.to_str()) != Some("toml") {
            continue;
        }
        let project = file
            .file_stem()
            .and_then(|s| s.to_str())
            .ok_or_else(|| anyhow::anyhow!("{} has no usable file stem", file.display()))?
            .to_string();
        let text = std::fs::read_to_string(&file)
            .with_context(|| format!("reading {}", file.display()))?;
        let parsed: PathSourceEntry = toml::from_str(&text)
            .with_context(|| format!("parsing {} as a path-source record", file.display()))?;
        out.push(PathSourceRecord {
            project,
            file,
            entry: parsed,
        });
    }
    out.sort_by(|a, b| a.project.cmp(&b.project));
    Ok(out)
}

/// Serialize a record back to its file's text. Round-trips
/// [`PathSourceEntry`] exactly, so `refresh --write` produces a diff of only
/// the fields that moved.
pub fn render_record(project: &str, entry: &PathSourceEntry) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# Path-source metadata record for `{project}`.\n\
         #\n\
         # THIS FILE IS THE SOURCE OF TRUTH and the only half a human edits.\n\
         # `../{SHIMS_DIR}/{project}/pyproject.toml` is GENERATED from it on every\n\
         # backend initialize and must not be edited.\n\
         #\n\
         # Every field is a FACT about the tree at `path`, cross-checked against\n\
         # the tree's own *.egg-info/PKG-INFO, config/extension.toml and setup.py\n\
         # on every run. A disagreement is a hard refusal naming this file.\n\
         # To adopt the tree's current facts:\n\
         #   pixi-build-retread path-source-refresh --pack <this pack dir> \\\n\
         #       --workspace <workspace root> --project {project} --write\n\n"
    ));
    out.push_str(&format!("path = {}\n", toml_string(&entry.path)));
    out.push_str(&format!("version = {}\n", toml_string(&entry.version)));
    if let Some(rp) = entry.requires_python.as_deref() {
        out.push_str(&format!("requires-python = {}\n", toml_string(rp)));
    }
    out.push_str(&format!("dependencies = {}\n", toml_array(&entry.dependencies)));
    if !entry.packages_include.is_empty() {
        out.push_str(&format!(
            "packages-include = {}\n",
            toml_array(&entry.packages_include)
        ));
    }
    if let Some(hash) = entry.source_hash.as_deref() {
        out.push_str(&format!(
            "\n# METAGEN-1. `dependencies` above was DERIVED by an isolated PEP 517\n\
             # metadata build of the tree at `path`, because that tree states them\n\
             # NOWHERE a reader can see -- no [project] table, no *.egg-info/PKG-INFO.\n\
             # This is the bounded content hash of that tree at the moment of the\n\
             # build; if the tree's hash today differs, this record is STALE and the\n\
             # next run rederives it. Editing the tree's setup.py, pyproject.toml,\n\
             # setup.cfg, MANIFEST.in or anything under config/ moves it.\n\
             source-hash = {}\n",
            toml_string(hash)
        ));
    }
    out
}

