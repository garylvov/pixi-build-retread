//! Static PEP 621 metadata for the workspace's local PyPI **path sources**,
//! supplied entirely from the PACK LAYER — a hand-editable record file beside
//! the pack's own manifest, and a GENERATED shim directory inside the pack
//! directory that the workspace manifest points its `path =` entry at.
//!
//! # The defect this closes
//!
//! pixi resolves `[pypi-dependencies]` entries of the form
//! `name = { path = "…", editable = true }` with its OWN uv (the frontend
//! resolver in `pixi_core::lock_file::resolve::pypi`), not with retread's
//! child uv. uv reads a path source's metadata statically only when the tree
//! carries a `[project]` table whose needed fields (`name`, `version`,
//! `requires-python`, `dependencies`) are present and are NOT listed in
//! `dynamic`. When they are not, uv logs
//!
//! ```text
//! No static `pyproject.toml` available for: pace-sim2real @ file:///… (FieldNotFound("project"))
//! Preparing metadata for: pace-sim2real @ file:///…
//! ```
//!
//! and runs a full PEP 517 `prepare_metadata_for_build_wheel`: pixi
//! instantiates a whole conda build environment for that one tree. On the
//! campaign's canonical 27-environment workspace that cost 1 714.7 s of a
//! 1 758 s lock for a 27-file, 40 KB source tree whose own build work is
//! 6.2 s.
//!
//! # Why the SHIM and not an overlay on the tree (the p6m → p6m-b change)
//!
//! p6m wrote the `[project]` block into the WORKSPACE copy of the real tree.
//! Correct and fast, but in production the workspace IS `imprint-data`, so
//! the overlay landed in `third_party/ProtoMotions` (an untracked new file)
//! and in `third_party/pace-sim2real/…/pyproject.toml` (an appended block) —
//! a dirty `git status` in trees we do not own, forever.
//!
//! p6m-b moves BOTH halves into the pack directory, where retread already
//! owns everything:
//!
//! * **the record** — `<pack>/path-sources/<project>.toml`, one file per
//!   project, hand-editable, the SOURCE OF TRUTH, and the only thing a human
//!   ever edits;
//! * **the shim** — `<pack>/sources/<project>/pyproject.toml`, GENERATED from
//!   that record on every `initialize`, never hand-edited, a pure function of
//!   the record plus the relative path to the real tree.
//!
//! The workspace manifest then reads
//!
//! ```toml
//! pace_sim2real = { path = "pypi-packs/isaaclab-2.3x-pack/sources/pace-sim2real", editable = true }
//! ```
//!
//! and **not one byte is written outside the pack directory**. The real tree
//! is reached from the shim by `[tool.setuptools] package-dir` /
//! `packages.find.where`, both relative, so the editable install's finder
//! resolves into the real tree and an edit there is live with no reinstall.
//!
//! It also removes p6m's one known limit. p6m's overlay was a side effect of
//! a backend invocation, so an environment declaring no retread pack
//! (`pm-mujoco`) could in principle resolve before any backend initialized.
//! The shim is tracked pack content: it is on disk before pixi starts, and
//! `initialize` only REFRESHES it.
//!
//! # Updatability — drift is loud, refresh is one command
//!
//! The record is a claim about a tree that upstream can bump under us. Every
//! `initialize` re-reads the tree's own statements of those facts
//! (`*.egg-info/PKG-INFO`, `config/extension.toml`, `setup.py`) and REFUSES,
//! naming the record file, the field, both values and the tree file that
//! disagrees. Nothing is silently overwritten in either direction:
//! `pixi-build-retread path-source-refresh --pack <dir> --workspace <dir>
//! [--write]` prints the diff and, with `--write`, rewrites the record FROM
//! the tree so the operator reviews one small diff.
//!
//! # The three things this module refuses to do
//!
//! * **Write outside the pack directory.** Every write goes through
//!   [`write_under_pack`], which fails if the target is not under the pack
//!   root. Pointing the writer at `third_party/…` fails the guard.
//! * **Write through a hardlink.** A staged workspace is `cp -al`'d out of a
//!   shared mirror. The shim file is written to a sibling temp and `rename`d
//!   over the name, which replaces the *directory entry*; every other link
//!   keeps the old inode. The written file is asserted to have one link.
//! * **Invent a path source.** If the consuming `pixi.toml` does not declare
//!   the shim's own path, the record is stale and nothing is written.

use std::collections::BTreeMap;
use std::path::{Component, Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use crate::config::RetreadConfig;

/// First line of the generated shim. Also the idempotence key and the
/// "do not hand-edit this" sign: the record file is the editable half.
pub const GENERATED_MARKER: &str =
    "# --- generated by pixi-build-retread (retread-path-source-metadata). Do not edit; edit the record beside the pack manifest. ---";

/// Last line of the generated shim.
pub const GENERATED_END: &str = "# --- end pixi-build-retread generated shim ---";

/// The PEP 621 fields uv needs statically.
pub const REQUIRED_STATIC_FIELDS: [&str; 4] =
    ["name", "version", "requires-python", "dependencies"];

/// Default directory, relative to the pack directory, holding the records.
/// One `<project>.toml` per project — "keyed by project", beside the pack's
/// own `retread-*.json` outputs.
pub const RECORDS_DIR_DEFAULT: &str = "path-sources";

/// Directory, relative to the pack directory, holding the generated shims.
/// `<pack>/sources/<project>/` is what the workspace manifest points at.
pub const SHIMS_DIR: &str = "sources";

/// One declared path source, read from `<pack>/path-sources/<project>.toml`.
///
/// **This file is the source of truth and the only hand-edited artifact.**
/// Everything in it is a FACT ABOUT THE REAL TREE, not a preference: it is
/// what a PEP 517 metadata build of that tree produces today, and every field
/// the tree also states for itself is cross-checked on every run.
#[derive(Debug, Clone, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct PathSourceEntry {
    /// Path to the REAL source tree, relative to the workspace root — the
    /// string the workspace manifest used before the shim replaced it.
    pub path: String,

    /// The project's version, as the tree's own build backend produces it.
    pub version: String,

    /// `requires-python`, e.g. `">=3.10"`. Omitted means the source declares
    /// none.
    #[serde(default)]
    pub requires_python: Option<String>,

    /// PEP 508 runtime dependencies, in the order the source declares them.
    #[serde(default)]
    pub dependencies: Vec<String>,

    /// Glob(s) selecting the importable packages inside the real tree.
    /// Defaults to `["<project-underscored>*"]`, which is what both live
    /// trees need (`pace_sim2real*`, `protomotions*`). Present because a
    /// tree with an unusual layout is a fact about the tree, not a
    /// preference.
    #[serde(default)]
    pub packages_include: Vec<String>,
}

impl PathSourceEntry {
    /// The `packages.find.include` globs to render, defaulted from the
    /// project name.
    pub fn include_globs(&self, project: &str) -> Vec<String> {
        if !self.packages_include.is_empty() {
            return self.packages_include.clone();
        }
        vec![format!("{}*", project.replace(['-', '.'], "_"))]
    }
}

/// A record file on disk, with the project it is keyed by.
#[derive(Debug, Clone)]
pub struct PathSourceRecord {
    /// The file stem — the project key. `pace-sim2real`, `protomotions`.
    pub project: String,
    /// The record file itself. Every refusal names it: it is what to edit.
    pub file: PathBuf,
    pub entry: PathSourceEntry,
}

/// What happened to one declared source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PathSourceOutcome {
    /// The shim was written or regenerated.
    Written { project: String, shim: PathBuf },
    /// The shim on disk already had identical bytes. No write.
    Unchanged { project: String, shim: PathBuf },
}

impl PathSourceOutcome {
    pub fn project(&self) -> &str {
        match self {
            Self::Written { project, .. } | Self::Unchanged { project, .. } => project,
        }
    }
    pub fn shim(&self) -> &Path {
        match self {
            Self::Written { shim, .. } | Self::Unchanged { shim, .. } => shim,
        }
    }
    pub fn verb(&self) -> &'static str {
        match self {
            Self::Written { .. } => "written",
            Self::Unchanged { .. } => "unchanged",
        }
    }
}

/// PEP 503 name normalization, so `pace_sim2real`, `pace-sim2real` and
/// `PACE.Sim2Real` compare equal.
pub fn normalize_dist_name(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut last_dash = false;
    for ch in name.chars() {
        if ch == '-' || ch == '_' || ch == '.' {
            if !last_dash {
                out.push('-');
                last_dash = true;
            }
        } else {
            out.push(ch.to_ascii_lowercase());
            last_dash = false;
        }
    }
    out
}

