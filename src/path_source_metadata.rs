/// THE production entry point, and the one the guards call.
///
/// Both the gate and the write live behind this single name on purpose: a
/// guard that called a lower-level helper would stay green when the call in
/// `Handler::initialize` is deleted, so the gate check is INSIDE here and the
/// wiring test drives `initialize` itself.
pub fn materialize_declared_path_sources(
    config: &RetreadConfig,
    workspace_dir: Option<&Path>,
    pack_manifest_path: Option<&Path>,
) -> Result<Vec<PathSourceOutcome>> {
    let records_dir = config
        .path_source_records
        .as_deref()
        .unwrap_or(RECORDS_DIR_DEFAULT);

    let pack_dir = pack_manifest_path.and_then(|p| p.parent()).map(Path::to_path_buf);

    if !config.path_source_metadata.unwrap_or(false) {
        if let Some(dir) = pack_dir.as_deref()
            && let Ok(found) = load_records(dir, records_dir)
            && !found.is_empty()
        {
            tracing::warn!(
                "{}/{} holds {} path-source record(s) but \
                 retread-path-source-metadata is not true: no shim will be \
                 refreshed and the frontend resolver will run a PEP 517 \
                 metadata build for each of them.",
                dir.display(),
                records_dir,
                found.len()
            );
        }
        return Ok(Vec::new());
    }

    let Some(pack_dir) = pack_dir else {
        bail!(
            "retread-path-source-metadata = true but this backend was not given \
             a manifest path, so the pack directory holding the records and the \
             generated shims cannot be located."
        );
    };
    let Some(workspace_root) = workspace_dir.filter(|dir| dir.join("pixi.toml").is_file()) else {
        bail!(
            "retread-path-source-metadata = true but this backend was not given \
             a workspace directory containing a pixi.toml. The real trees are \
             located relative to the workspace root, and the shim's own path \
             must be the one the workspace manifest declares."
        );
    };
    // ONE AUTHORITY FOR "WHAT THE RECORDS ARE" (N27-RETREAD-115). This used to
    // call `generate_shims`, which loads `<pack>/<records_dir>/<project>.toml`
    // from disk and refused when that directory was empty. SHIM-AUTO-3 made the
    // `path-source-manifest` verb DERIVE the same records from the workspace
    // manifest plus the trees' own metadata and stopped writing those files, so
    // the two producers of one capability read two different paths and the gate
    // key became a lock-killing precondition with no producer: C36 arm 3
    // (job 6082196) died at the first `initialize` RPC in 0.17 s of CPU on the
    // refusal this block used to raise. The backend now runs the SAME
    // derivation, so `retread-path-source-metadata = true` is a gate WITH a
    // producer and no file has to exist anywhere.
    let manifest_file = workspace_root.join("pixi.toml");
    let manifest_text = std::fs::read_to_string(&manifest_file)
        .with_context(|| format!("reading {}", manifest_file.display()))?;
    // METAGEN-1. The last-resort dependency reader, or `None` when
    // `retread-derive-editable-metadata = false`. Built here and not inside the
    // derivation so the switch has exactly ONE reader in production.
    let deriver = crate::derived_editable_metadata::ConfiguredDeriver::from_config(
        config.derive_editable_metadata,
        config.path_source_metadata_store.as_deref(),
        &|key| std::env::var(key).ok(),
        std::env::temp_dir().join(format!("retread-metagen-{}", std::process::id())),
    );
    let dynamic = deriver
        .as_ref()
        .map(|d| d as &dyn DynamicDependencySource);
    let generated_records = config.path_source_generated_records.unwrap_or(true);
    let backend = backend_records(&pack_dir, workspace_root, records_dir, &manifest_text, dynamic, generated_records)?;
    // THE ROWS. METAGEN-2's `### PATH SOURCE FACTS` row for EVERY source --
    // which producer supplied its dependencies, how many `Requires-Dist` the
    // egg-info stated, and whether the pyproject leaves them dynamic -- then
    // METAGEN-1's `### EDITABLE METADATA DERIVED` row for each source whose
    // dependencies had to be BUILT. A run in which nothing was built is no
    // longer a silent run: the row that used to be missing is exactly the one
    // worth reading (`deps=absent` is the `dependencies = []` drop).
    for row in &backend.metadata_rows {
        tracing::info!("{}", row);
    }
    if backend.records.is_empty() {
        bail!(
            "retread-path-source-metadata = true but {} declares no \
             `[pypi-dependencies]` path source pointing into {}/{}. The records \
             are DERIVED from the manifest and the trees — the same derivation \
             `path-source-manifest` runs — so nothing under {}/{} is required or \
             read to satisfy this key. A gate with no producer is a defect: lock \
             the EFFECTIVE manifest (`pixi-build-retread path-source-manifest \
             --pack {} --workspace {} --out <file>`) or drop the key.{}",
            manifest_file.display(),
            pack_dir.display(),
            SHIMS_DIR,
            pack_dir.display(),
            records_dir,
            pack_dir.display(),
            workspace_root.display(),
            if backend.elsewhere.is_empty() {
                String::new()
            } else {
                format!(
                    " Derived beside this pack but declared at no shim of it: {}.",
                    backend.elsewhere.join(", ")
                )
            }
        );
    }
    // THE ROW. A derivation nobody can read back is the same defect as a record
    // nobody wrote, so the backend prints what it derived before it writes.
    tracing::info!("{}", backend.row(&pack_dir));
    let outcomes = generate_shims_from(
        &pack_dir,
        workspace_root,
        None,
        &manifest_text,
        &backend.records,
    )?;
    Ok(outcomes)
}

/// The records ONE pack's backend stands behind, derived — never loaded.
///
/// [`derive_records`] answers "which source does which pack stand in for" from
/// the manifest's SCOPES, which is the right question for the verb because the
/// verb is given every pack at once and can break a tie with
/// `pack_builds_project`. A backend is given exactly one pack and cannot see
/// the others, so a source co-declared beside two packs would be derived for
/// whichever pack happened to be asking. The manifest itself settles it: an
/// effective manifest points each source at exactly one pack's
/// `sources/<project>`, so a derived record whose shim THIS pack's directory
/// does not own belongs to another pack's backend and is reported, never
/// written. It is the same reader/writer tie `materialize_one` enforces one
/// level down, asked as a selection instead of a refusal.
#[derive(Debug, Clone)]
pub struct BackendRecords {
    /// The records this pack must materialise, in project order.
    pub records: Vec<PathSourceRecord>,
    /// How many of them a record file on disk CONFIRMED field-for-field.
    pub confirmed: usize,
    /// Sources derived beside this pack whose shim the manifest points
    /// elsewhere — another pack's backend owns them.
    pub elsewhere: Vec<String>,
    /// METAGEN-2's `### PATH SOURCE FACTS` rows followed by METAGEN-1's
    /// `### EDITABLE METADATA DERIVED` rows, carried out so `initialize` can log
    /// them where a verb would print them.
    pub metadata_rows: Vec<String>,
}

impl BackendRecords {
    /// The evidence row, printed by `initialize` before anything is written.
    pub fn row(&self, pack_dir: &Path) -> String {
        format!(
            "### PATH SOURCE RECORDS backend derived={} confirmed={} source={} pack={} elsewhere={}",
            self.records.len(),
            self.confirmed,
            if !self.records.is_empty() && self.confirmed == self.records.len() {
                "file"
            } else {
                "derived"
            },
            pack_dir.display(),
            if self.elsewhere.is_empty() {
                "none".to_string()
            } else {
                self.elsewhere.join(",")
            },
        )
    }
}

/// Derive the records for one pack. See [`BackendRecords`].
pub fn backend_records(
    pack_dir: &Path,
    workspace_root: &Path,
    records_dir: &str,
    manifest_text: &str,
    dynamic: Option<&dyn DynamicDependencySource>,
    generated_records: bool,
) -> Result<BackendRecords> {
    let canonical_root = workspace_root
        .canonicalize()
        .with_context(|| format!("canonicalizing {}", workspace_root.display()))?;
    let packs = [pack_dir.to_path_buf()];
    let derivation = derive_records(&packs, workspace_root, records_dir, manifest_text, dynamic, generated_records)?;
    let mut records = Vec::new();
    let mut confirmed = 0usize;
    let mut elsewhere = derivation.elsewhere;
    // METAGEN-2: the decision rows come out on the same channel as the build
    // rows, facts first, so the backend's `tracing` output and the verb's stdout
    // carry the same evidence in the same order.
    let mut metadata_rows = derivation.facts_rows;
    metadata_rows.extend(derivation.metadata_rows);
    for record in derivation.records {
        let shim_rel = pathdiff_from_root(&canonical_root, &record.shim)?;
        if declares_path(manifest_text, &shim_rel) {
            if record.confirmed {
                confirmed += 1;
            }
            records.push(record.record);
        } else {
            elsewhere.push(format!(
                "{} (this pack's shim would be \"{shim_rel}\", which the manifest \
                 does not declare)",
                record.record.project
            ));
        }
    }
    Ok(BackendRecords {
        records,
        confirmed,
        elsewhere,
        metadata_rows,
    })
}

/// Generate (or refresh) every shim this pack's records describe.
///
/// This is the SINGLE writer, shared by `Handler::initialize` and by the
/// `path-source-refresh --shims` CLI verb — the command a developer runs once
/// to materialize the shim they then COMMIT as pack content. The two callers
/// must not drift: a shim a developer committed and a shim `initialize`
/// regenerates are the same bytes, which is what makes `initialize` a no-op on
/// a clean checkout.
pub fn generate_shims(
    pack_dir: &Path,
    workspace_root: &Path,
    records_dir: &str,
    only: Option<&str>,
) -> Result<Vec<PathSourceOutcome>> {
    let manifest_text = std::fs::read_to_string(workspace_root.join("pixi.toml"))
        .with_context(|| format!("reading {}", workspace_root.join("pixi.toml").display()))?;
    generate_shims_against(pack_dir, workspace_root, records_dir, only, &manifest_text)
}

/// [`generate_shims`], but against a manifest text the caller supplies.
///
/// The reader/writer tie inside `materialize_one` asks "does the manifest that
/// is about to be resolved declare this shim?". When retread GENERATES that
/// manifest (see [`plan_effective_manifest`]) the file on disk is still the
/// canonical one, which by construction still points at the real tree — so the
/// tie has to be checked against the text about to be locked, not against the
/// text on disk. Same writer, same bytes, one honest question.
pub fn generate_shims_against(
    pack_dir: &Path,
    workspace_root: &Path,
    records_dir: &str,
    only: Option<&str>,
    manifest_text: &str,
) -> Result<Vec<PathSourceOutcome>> {
    // A pack is identified by its own manifest. Without this, any directory
    // handed to `--pack` becomes a write root, and the one thing this
    // capability must never do is write into a directory that is not a pack.
    if !pack_dir.join("pixi.toml").is_file() {
        bail!(
            "{} is not a pack directory: it holds no pixi.toml. retread \
             generates path-source shims into a PACK and nowhere else.",
            pack_dir.display()
        );
    }
    let records = load_records(pack_dir, records_dir)?;
    generate_shims_from(pack_dir, workspace_root, only, manifest_text, &records)
}

/// [`generate_shims_against`], but against records the caller already holds.
///
/// The ONE writer, kept behind one name so the two producers of records — the
/// files on disk that `path-source-refresh` maintains, and the derivation in
/// [`derive_records`] — write byte-identical shims. A second writer for the
/// derived half would be exactly the drift the `--shims` verb's doc comment
/// warns about one function up.
pub fn generate_shims_from(
    pack_dir: &Path,
    workspace_root: &Path,
    only: Option<&str>,
    manifest_text: &str,
    records: &[PathSourceRecord],
) -> Result<Vec<PathSourceOutcome>> {
    if !pack_dir.join("pixi.toml").is_file() {
        bail!(
            "{} is not a pack directory: it holds no pixi.toml. retread \
             generates path-source shims into a PACK and nowhere else.",
            pack_dir.display()
        );
    }
    let mut outcomes = Vec::with_capacity(records.len());
    for record in records {
        if let Some(only) = only
            && only != record.project
        {
            continue;
        }
        let outcome = materialize_one(pack_dir, workspace_root, manifest_text, record)
            .with_context(|| format!("path-source record {}", record.file.display()))?;
        tracing::info!(
            "retread-path-source-metadata: {} {} ({})",
            outcome.verb(),
            outcome.shim().display(),
            outcome.project(),
        );
        outcomes.push(outcome);
    }
    Ok(outcomes)
}

fn materialize_one(
    pack_dir: &Path,
    workspace_root: &Path,
    manifest_text: &str,
    record: &PathSourceRecord,
) -> Result<PathSourceOutcome> {
    let entry = &record.entry;

    // ---- the record itself -------------------------------------------------
    if entry.path.trim().is_empty() {
        bail!("`path` is empty");
    }
    if entry.version.trim().is_empty() {
        bail!("`version` is empty: uv needs a static version or it builds anyway");
    }

    // ---- where the REAL tree is --------------------------------------------
    let rel = Path::new(&entry.path);
    if rel.is_absolute() {
        bail!("`path` must be relative to the workspace root, got {}", entry.path);
    }
    if rel
        .components()
        .any(|c| matches!(c, Component::ParentDir | Component::Prefix(_) | Component::RootDir))
    {
        bail!("`path` may not escape the workspace root, got {}", entry.path);
    }
    let real_dir = workspace_root.join(rel);
    if !real_dir.is_dir() {
        bail!("{} is not a directory", real_dir.display());
    }
    let canonical_root = workspace_root
        .canonicalize()
        .with_context(|| format!("canonicalizing {}", workspace_root.display()))?;
    let canonical_real = real_dir
        .canonicalize()
        .with_context(|| format!("canonicalizing {}", real_dir.display()))?;
    if !canonical_real.starts_with(&canonical_root) {
        bail!(
            "{} resolves to {}, which is outside the workspace root {}",
            entry.path,
            canonical_real.display(),
            canonical_root.display()
        );
    }

    // ---- the facts must still be the tree's facts --------------------------
    let facts = tree_facts(&real_dir)?;
    check_drift(record, &facts)?;

    // ---- where the SHIM goes, and the reader/writer tie --------------------
    let shim_dir = pack_dir.join(SHIMS_DIR).join(&record.project);
    let shim_rel_to_ws = pathdiff_from_root(&canonical_root, &shim_dir)?;
    if !manifest_text.contains(&format!("\"{shim_rel_to_ws}\""))
        && !manifest_text.contains(&format!("'{shim_rel_to_ws}'"))
    {
        bail!(
            "the workspace manifest declares no path source `{shim_rel_to_ws}`; \
             refusing to generate a shim nothing resolves. Point the \
             `[pypi-dependencies]` entry for `{}` at it:\n    {} = {{ path = \
             \"{shim_rel_to_ws}\", editable = true }}",
            record.project,
            record.project.replace('-', "_"),
        );
    }

    // ---- relative path from the SHIM back to the real tree -----------------
    let rel_to_real = relative_from_shim(&shim_rel_to_ws, &entry.path);

    // ---- compose and write -------------------------------------------------
    let composed = render_shim_pyproject(&record.project, entry, &rel_to_real);
    let shim_file = shim_dir.join("pyproject.toml");
    let existing = match std::fs::read_to_string(&shim_file) {
        Ok(text) => Some(text),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => None,
        Err(err) => return Err(err).with_context(|| format!("reading {}", shim_file.display())),
    };
    if existing.as_deref() == Some(composed.as_str()) {
        verify_shim(&shim_file, &record.project, entry)?;
        return Ok(PathSourceOutcome::Unchanged {
            project: record.project.clone(),
            shim: shim_dir,
        });
    }
    write_under_pack(pack_dir, &shim_dir, None)?;
    std::fs::create_dir_all(&shim_dir)
        .with_context(|| format!("creating {}", shim_dir.display()))?;
    write_under_pack(pack_dir, &shim_file, Some(composed.as_str()))?;
    verify_shim(&shim_file, &record.project, entry)?;
    Ok(PathSourceOutcome::Written {
        project: record.project.clone(),
        shim: shim_dir,
    })
}

/// The generated shim `pyproject.toml`. A pure function of the record and the
/// relative path from the shim to the real tree — regenerating it is always a
/// no-op when nothing moved, which is what makes the file safe to track.
///
/// The shim carries a `[build-system]` because it IS its own project root:
/// unlike p6m's in-tree overlay, the real tree's `setup.py` never runs for
/// this dist. `package-dir` and `packages.find.where` both point at the real
/// tree, so setuptools' editable finder maps the package names onto files
/// under the real tree and an edit there is live with no reinstall.
pub fn render_shim_pyproject(project: &str, entry: &PathSourceEntry, rel_to_real: &str) -> String {
    let mut out = String::new();
    out.push_str(GENERATED_MARKER);
    out.push('\n');
    out.push_str(
        "#\n\
         # Source of truth: ../../path-sources/<project>.toml, beside the pack\n\
         # manifest. This file is a pure function of that record plus the\n\
         # relative path to the real tree, regenerated on every initialize.\n\
         #\n\
         # It exists so pixi's own resolver can read this source's metadata\n\
         # without running a PEP 517 metadata build (which costs a whole conda\n\
         # build environment per tree). The importable code is NOT here: it is\n\
         # the real tree named below, reached by a relative package-dir, so an\n\
         # editable install of this shim imports and live-edits that tree.\n",
    );
    out.push_str("\n[build-system]\n");
    out.push_str("requires = [\"setuptools>=64\"]\n");
    out.push_str("build-backend = \"setuptools.build_meta\"\n");
    out.push_str("\n[project]\n");
    out.push_str(&format!("name = {}\n", toml_string(project)));
    out.push_str(&format!("version = {}\n", toml_string(&entry.version)));
    if let Some(rp) = entry.requires_python.as_deref() {
        out.push_str(&format!("requires-python = {}\n", toml_string(rp)));
    }
    out.push_str(&format!(
        "dependencies = {}\n",
        toml_array(&entry.dependencies)
    ));
    out.push_str("\n[tool.setuptools.package-dir]\n");
    out.push_str(&format!("\"\" = {}\n", toml_string(rel_to_real)));
    out.push_str("\n[tool.setuptools.packages.find]\n");
    out.push_str(&format!("where = [{}]\n", toml_string(rel_to_real)));
    out.push_str(&format!(
        "include = {}\n",
        toml_array(&entry.include_globs(project))
    ));
    out.push_str("namespaces = true\n");
    out.push_str(GENERATED_END);
    out.push('\n');
    out
}

fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn toml_array(values: &[String]) -> String {
    if values.is_empty() {
        return "[]".to_string();
    }
    format!(
        "[{}]",
        values
            .iter()
            .map(|v| toml_string(v))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// `a/b/c` from the workspace root to `target`, refusing anything outside it.
fn pathdiff_from_root(canonical_root: &Path, target: &Path) -> Result<String> {
    // The shim may not exist yet, so canonicalize the deepest existing parent
    // and re-attach the tail.
    let mut tail = Vec::new();
    let mut probe = target.to_path_buf();
    let canonical = loop {
        match probe.canonicalize() {
            Ok(c) => break c,
            Err(_) => {
                let Some(name) = probe.file_name().map(|n| n.to_os_string()) else {
                    bail!("cannot locate {} under a workspace root", target.display());
                };
                tail.push(name);
                if !probe.pop() {
                    bail!("cannot locate {} under a workspace root", target.display());
                }
            }
        }
    };
    let mut full = canonical;
    for name in tail.iter().rev() {
        full.push(name);
    }
    let rel = full.strip_prefix(canonical_root).map_err(|_| {
        anyhow::anyhow!(
            "{} resolves to {}, which is outside the workspace root {}",
            target.display(),
            full.display(),
            canonical_root.display()
        )
    })?;
    Ok(rel.to_string_lossy().replace('\\', "/"))
}

/// The relative path a file inside `shim_rel` uses to reach `real_rel`, both
/// given relative to the same workspace root.
fn relative_from_shim(shim_rel: &str, real_rel: &str) -> String {
    let up = shim_rel.split('/').filter(|s| !s.is_empty()).count();
    let mut out = String::new();
    for _ in 0..up {
        out.push_str("../");
    }
    out.push_str(real_rel);
    out
}

/// EVERY write in this module goes through here. `text: None` means "I am
/// about to create this directory".
///
/// The scope check is the point: retread owns the pack directory and nothing
/// else, and the whole reason p6m-b exists is that p6m wrote into trees we do
/// not own. Pointing the writer at `third_party/…` fails here, which is the
/// RED control for this capability.
fn write_under_pack(pack_dir: &Path, target: &Path, text: Option<&str>) -> Result<()> {
    let canonical_pack = pack_dir
        .canonicalize()
        .with_context(|| format!("canonicalizing pack directory {}", pack_dir.display()))?;
    // Resolve as far as exists, then re-attach — the target may be new.
    let mut tail = Vec::new();
    let mut probe = target.to_path_buf();
    let resolved = loop {
        match probe.canonicalize() {
            Ok(c) => break c,
            Err(_) => {
                let Some(name) = probe.file_name().map(|n| n.to_os_string()) else {
                    bail!(
                        "refusing to write {}: it has no locatable parent",
                        target.display()
                    );
                };
                tail.push(name);
                if !probe.pop() {
                    bail!(
                        "refusing to write {}: it has no locatable parent",
                        target.display()
                    );
                }
            }
        }
    };
    let mut full = resolved;
    for name in tail.iter().rev() {
        full.push(name);
    }
    if !full.starts_with(&canonical_pack) {
        bail!(
            "refusing to write {} (resolves to {}): it is outside this pack's own \
             directory {}. retread writes generated shims into the pack layer and \
             NOWHERE else — never into a source tree.",
            target.display(),
            full.display(),
            canonical_pack.display()
        );
    }
    let Some(text) = text else {
        return Ok(());
    };
    atomic_replace(target, text)
}

/// Replace `file` with `text` WITHOUT ever opening `file` for writing.
///
/// A staged workspace hardlinks its trees out of a shared mirror, so a target
/// can be one of N links to an inode the job must not modify. Writing in
/// place writes through every one of those links; writing a sibling and
/// renaming replaces the directory ENTRY only.
fn atomic_replace(file: &Path, text: &str) -> Result<()> {
    let dir = file
        .parent()
        .ok_or_else(|| anyhow::anyhow!("{} has no parent directory", file.display()))?;
    let tmp = dir.join(format!(
        ".{}.retread-p6mb.{}.tmp",
        file.file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("pyproject.toml"),
        std::process::id()
    ));
    let _ = std::fs::remove_file(&tmp);
    std::fs::write(&tmp, text).with_context(|| format!("writing {}", tmp.display()))?;
    std::fs::rename(&tmp, file)
        .with_context(|| format!("renaming {} onto {}", tmp.display(), file.display()))?;
    Ok(())
}

/// Read the shim back and prove it is what uv needs. A shim that produced
/// something uv would refuse is worse than none: it is a silent return to the
/// metadata build with a generated file to explain.
fn verify_shim(file: &Path, project: &str, entry: &PathSourceEntry) -> Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt as _;
        let links = std::fs::metadata(file)
            .with_context(|| format!("stat {}", file.display()))?
            .nlink();
        if links != 1 {
            bail!(
                "{} has {links} hard links after the write; a shared inode may \
                 have been modified",
                file.display()
            );
        }
    }
    let text = std::fs::read_to_string(file)
        .with_context(|| format!("re-reading {}", file.display()))?;
    let parsed: toml::Value =
        toml::from_str(&text).with_context(|| format!("re-parsing {}", file.display()))?;
    let table = parsed
        .get("project")
        .ok_or_else(|| anyhow::anyhow!("{} has no [project] table", file.display()))?;
    let name = table.get("name").and_then(|v| v.as_str()).unwrap_or_default();
    if normalize_dist_name(name) != normalize_dist_name(project) {
        bail!("{} declares name {name}, wanted {project}", file.display());
    }
    let version = table.get("version").and_then(|v| v.as_str()).unwrap_or_default();
    if version != entry.version {
        bail!(
            "{} declares version {version}, wanted {}",
            file.display(),
            entry.version
        );
    }
    if table.get("dependencies").and_then(|v| v.as_array()).is_none() {
        bail!("{} has no static `dependencies` array", file.display());
    }
    if entry.requires_python.is_some() && table.get("requires-python").is_none() {
        bail!("{} lost its `requires-python`", file.display());
    }
    if let Some(dynamic) = table.get("dynamic").and_then(|v| v.as_array()) {
        for value in dynamic {
            let field = value.as_str().unwrap_or_default().to_ascii_lowercase();
            if REQUIRED_STATIC_FIELDS.contains(&field.as_str()) {
                bail!(
                    "{} lists `{field}` as dynamic, which forces the metadata \
                     build this shim exists to avoid",
                    file.display()
                );
            }
        }
    }
    // The shim must point somewhere: a shim with no package-dir installs an
    // empty distribution, which imports as a missing module at runtime.
    let package_dir = parsed
        .get("tool")
        .and_then(|t| t.get("setuptools"))
        .and_then(|s| s.get("package-dir"))
        .and_then(|p| p.get(""))
        .and_then(|v| v.as_str());
    let Some(package_dir) = package_dir else {
        bail!(
            "{} has no [tool.setuptools.package-dir] \"\" entry, so an editable \
             install of it would contain no code",
            file.display()
        );
    };
    let resolved = file
        .parent()
        .map(|d| d.join(package_dir))
        .ok_or_else(|| anyhow::anyhow!("{} has no parent", file.display()))?;
    if !resolved.is_dir() {
        bail!(
            "{} points package-dir at {}, which resolves to {} and is not a \
             directory",
            file.display(),
            package_dir,
            resolved.display()
        );
    }
    Ok(())
}

fn find_pkg_info(dir: &Path) -> Result<Option<PathBuf>> {
    let mut found: Option<PathBuf> = None;
    for entry in std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let entry = entry?;
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let is_egg_info = path
            .file_name()
            .and_then(|n| n.to_str())
            .is_some_and(|n| n.ends_with(".egg-info"));
        if !is_egg_info {
            continue;
        }
        let candidate = path.join("PKG-INFO");
        if candidate.is_file() {
            // More than one egg-info is ambiguous: do not guess which one the
            // build would have produced.
            if found.is_some() {
                return Ok(None);
            }
            found = Some(candidate);
        }
    }
    Ok(found)
}

// ---------------------------------------------------------------------------
// the EFFECTIVE MANIFEST — retread generates the repoint the operator used to
// make by hand (SHIM-AUTO-1)
// ---------------------------------------------------------------------------
//
// # Why this is not a backend hook
//
// The shim only pays off if pixi's frontend resolver reads the SHIM's static
// `[project]` table instead of running a PEP 517 metadata build on the real
// tree. That decision is made when pixi parses the workspace manifest, which
// happens BEFORE any build backend process exists — and for an environment
// that declares no retread pack (`pm-mujoco`) the pypi resolve can complete
// without retread ever being spawned. So `Handler::initialize` is structurally
// too late to repoint an entry, and `write_under_pack` would refuse the write
// anyway: the workspace manifest is not pack content.
//
// The manifest repoint therefore belongs to a PRE-LOCK step, and this is it.
// It never writes the canonical manifest. It reads the canonical bytes and
// emits an EFFECTIVE manifest that the lock driver stages into the disposable
// workspace it already builds — the same slot the hand-made
// `b1-scratch/pixi.toml.p6mb` occupied, now derived rather than typed.

/// One `[pypi-dependencies]` entry the transform repointed at a pack shim.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShimRewrite {
    /// The record's project key, e.g. `pace-sim2real`.
    pub project: String,
    /// The real tree, relative to the workspace root — what the canonical
    /// manifest declares.
    pub from: String,
    /// The generated shim directory, relative to the workspace root — what the
    /// effective manifest declares.
    pub to: String,
    /// The pack directory that owns the record and the shim.
    pub pack: PathBuf,
    /// How many manifest lines carried the entry. Three `pm-*` features share
    /// one `protomotions` record, so this is routinely > 1.
    pub lines: usize,
    /// True when the manifest ALREADY declared the shim, so nothing moved.
    /// Re-running the transform on its own output is a no-op, which is what
    /// makes the effective manifest safe to regenerate on every lock.
    pub already: bool,
}

impl ShimRewrite {
    /// The evidence row. One per repointed entry, printed by the verb and by
    /// any caller that wants the transform legible in a job log.
    pub fn row(&self) -> String {
        format!(
            "### PACK SHIM name={} from={} to={} lines={} reason={}",
            self.project,
            self.from,
            self.to,
            self.lines,
            if self.already {
                "already-declared"
            } else {
                "materialised"
            }
        )
    }
}

// ---------------------------------------------------------------------------
// DERIVATION — the record is a FUNCTION of the manifest and the tree
// ---------------------------------------------------------------------------
//
// WHY THIS EXISTS. The record file was described above as "the only
// hand-edited artifact". Measured against production that claim was the whole
// defect: `pypi-packs/*/path-sources/` does not exist in `imprint-data` at
// all, so the daily relock's default `PACK_SHIM_MODE=on` refused at
// `path-sources holds no <project>.toml record` (SHIM-PROOF-1) and the one
// arm that ever passed did so because its harness MANUFACTURED the two
// records into a disposable workspace from shell literals. Writing those
// literals into `imprint-data` by hand would have made the manufactured
// artifact permanent instead of removing it.
//
// Every field of both fabricated records is a fact something else already
// states:
//
// | field            | who already states it                                  |
// |------------------|--------------------------------------------------------|
// | project key      | the workspace manifest's `[pypi-dependencies]` KEY      |
// | `path`           | that entry's own `path =` value                         |
// | `version`        | the tree (`*.egg-info/PKG-INFO`, `config/extension.toml`, `setup.py`) |
// | `requires-python`| the same three readers                                  |
// | `dependencies`   | PKG-INFO's `Requires-Dist` lines                        |
// | target pack      | the manifest scope that declares BOTH the pack and the source |
//
// So the record is derived, and a record file on disk may only CONFIRM it.
// Nothing is required to exist, and a disagreement is a loud refusal naming
// both sides rather than a silent preference for either.

/// One record the derivation produced, with the evidence for where each half
/// of it came from.
#[derive(Debug, Clone)]
pub struct DerivedRecord {
    /// The record itself. `record.file` names the CONFIRMING file — which may
    /// not exist; it is still the path a refusal tells the operator to look at.
    pub record: PathSourceRecord,
    /// The pack that stands in for this source.
    pub pack: PathBuf,
    /// True when a record file existed on disk and agreed field-for-field.
    pub confirmed: bool,
    /// The generated shim directory, absolute.
    pub shim: PathBuf,
}

impl DerivedRecord {
    /// The evidence row, one per derived record.
    pub fn row(&self) -> String {
        format!(
            "### PATH SOURCE RECORD project={} source={} pack={} derived={} shim={}",
            self.record.project,
            self.record.entry.path,
            self.pack.display(),
            if self.confirmed { "confirmed" } else { "yes" },
            self.shim.display()
        )
    }
}

/// One manifest scope: the default feature, or one `[feature.X]` block.
///
/// A SCOPE, not an environment. Feature-to-environment resolution is
/// `workspace::WorkspaceManifest`'s job and it deliberately is not used here:
/// the question this asks is "which pack does this source sit beside in the
/// manifest as written", and env inheritance would make every source sit
/// beside every pack of every env that activates it.
#[derive(Debug, Default)]
struct ManifestScope {
    name: String,
    /// `path` values of conda `[dependencies]` entries — the packs.
    conda_paths: Vec<String>,
    /// `(raw key, path)` of `[pypi-dependencies]` entries declaring a `path`.
    pypi_paths: Vec<(String, String)>,
}

/// Collect the `path` values of every `path`-declaring entry in `table`.
fn path_entries(container: &toml::Value, key: &str) -> Vec<(String, String)> {
    let underscored = key.replace('-', "_");
    let Some(table) = container
        .get(key)
        .or_else(|| container.get(underscored.as_str()))
        .and_then(|v| v.as_table())
    else {
        return Vec::new();
    };
    table
        .iter()
        .filter_map(|(name, value)| {
            let path = value.as_table()?.get("path")?.as_str()?;
            Some((name.clone(), path.to_string()))
        })
        .collect()
}

/// Both dependency tables of one scope, including everything the scope's
/// `[target.<sel>.…]` sub-tables declare.
///
/// The targets are read because a source declared only under `target.unix`
/// would otherwise be INVISIBLE to the derivation while still being a real
/// PEP 517 metadata build in the lock — a silent miss, which is the one
/// failure mode this whole capability exists to make impossible.
fn scope_from(name: &str, container: &toml::Value) -> ManifestScope {
    let mut scope = ManifestScope {
        name: name.to_string(),
        conda_paths: path_entries(container, "dependencies")
            .into_iter()
            .map(|(_, p)| p)
            .collect(),
        pypi_paths: path_entries(container, "pypi-dependencies"),
    };
    if let Some(targets) = container.get("target").and_then(|v| v.as_table()) {
        for target in targets.values() {
            scope
                .conda_paths
                .extend(path_entries(target, "dependencies").into_iter().map(|(_, p)| p));
            scope
                .pypi_paths
                .extend(path_entries(target, "pypi-dependencies"));
        }
    }
    scope
}

/// Every scope of the manifest: the root table, then each `[feature.X]`.
fn manifest_scopes(manifest_text: &str) -> Result<Vec<ManifestScope>> {
    let parsed: toml::Value = toml::from_str(manifest_text)
        .context("parsing the workspace manifest to derive its path sources")?;
    let mut scopes = vec![scope_from("(default)", &parsed)];
    if let Some(features) = parsed.get("feature").and_then(|v| v.as_table()) {
        for (name, value) in features {
            scopes.push(scope_from(name, value));
        }
    }
    Ok(scopes)
}

/// `workspace_root/rel`, canonicalized, or `None` when nothing is there.
fn resolve_under(canonical_root: &Path, rel: &str) -> Option<PathBuf> {
    canonical_root.join(rel).canonicalize().ok()
}

/// True when `pack`'s own manifest declares a wheel for `project` — the
/// tiebreak when one scope declares more than one pack.
///
/// It is a FACT and not a preference: a pack that builds the project's own
/// distribution is the pack that stands in for its tree. `pm-isaaclab`
/// declares `isaaclab-2.3x-pack` and `protomotions-deps-pack` side by side and
/// only the latter carries
/// `[package.build.config.retread-wheels] protomotions = { git = … }`.
fn pack_builds_project(pack_dir: &Path, project: &str) -> Result<bool> {
    let manifest = pack_dir.join("pixi.toml");
    let text = std::fs::read_to_string(&manifest)
        .with_context(|| format!("reading {}", manifest.display()))?;
    let parsed: toml::Value = toml::from_str(&text)
        .with_context(|| format!("parsing {} as a pack manifest", manifest.display()))?;
    let Some(wheels) = parsed
        .get("package")
        .and_then(|p| p.get("build"))
        .and_then(|b| b.get("config"))
        .and_then(|c| c.get("retread-wheels"))
        .and_then(|w| w.as_table())
    else {
        return Ok(false);
    };
    Ok(wheels
        .keys()
        .any(|k| normalize_dist_name(k) == normalize_dist_name(project)))
}

/// What one derivation produced: the records, and every source it deliberately
/// did NOT claim.
///
/// `elsewhere` exists because the derivation is now run by TWO callers with
/// different visibility. The verb is handed every pack at once and can break a
/// two-pack tie with `pack_builds_project`; a BACKEND is handed exactly one
/// pack and cannot see its siblings, so a source co-declared beside two packs
/// (`pm-isaaclab` declares `isaaclab-2.3x-pack` and `protomotions-deps-pack`
/// side by side) would otherwise be claimed by whichever backend asked. A
/// dropped source with no row is exactly the silent miss this capability
/// exists to make impossible, so it is carried out and every caller states
/// what it does with it.
#[derive(Debug, Clone, Default)]
pub struct Derivation {
    pub records: Vec<DerivedRecord>,
    pub elsewhere: Vec<String>,
    /// METAGEN-1. One `### EDITABLE METADATA DERIVED` row per source whose
    /// dependencies had to be BUILT because the tree states them nowhere.
    ///
    /// It is carried out rather than printed here for the reason `elsewhere`
    /// is: the derivation has two callers with different output channels (a
    /// verb writing to stdout, a backend writing to `tracing`), and a row that
    /// only one of them can emit is a producer half the system cannot read.
    pub metadata_rows: Vec<String>,
    /// METAGEN-2 (N27-RETREAD-223). One `### PATH SOURCE FACTS` row per source,
    /// ALWAYS — the decision itself, not the build. Separate from
    /// `metadata_rows` because that vector's emptiness is a claim several
    /// guards make ("a silent run is a run in which nothing was built"), while
    /// this vector is never empty for a manifest that declares a source: the
    /// case worth reading is exactly the one that used to print nothing
    /// (`deps=absent`). Both vectors reach the same output channel — every
    /// caller that prints one prints the other, facts first.
    pub facts_rows: Vec<String>,
}

/// METAGEN-1's seam into the derivation: the LAST-RESORT reader of a path
/// source's dependencies, consulted only when the tree states them nowhere.
///
/// `None` at the call site is the `retread-derive-editable-metadata = false`
/// arm and reproduces the behaviour before this existed exactly — which is
/// what makes the opt-out a thing a guard can drive rather than a claim.
pub trait DynamicDependencySource {
    /// Derive the tree's core metadata. A failure here must REACH THE CALLER:
    /// falling back to the frontend's prefix-parented PEP 517 build is the
    /// 1295.6 s this whole capability removes, and taking it silently would
    /// hide the failure that needs fixing.
    fn derive(&self, tree: &Path) -> Result<crate::derived_editable_metadata::Derived>;
}

/// A manifest entry that already points at a generated shim: recover the real
/// tree it stands for from the shim's own `package-dir`.
///
/// This is what keeps the transform a FIXED POINT once the records are derived
/// rather than read. On an already-effective manifest the real tree is no
/// longer declared anywhere, so the only remaining statement of it is the shim
/// the previous run generated — and reading it back is a real reader for a
/// real writer, not a special case.
fn real_tree_behind_shim(shim_dir: &Path, canonical_root: &Path) -> Result<String> {
    let file = shim_dir.join("pyproject.toml");
    let text = std::fs::read_to_string(&file).with_context(|| {
        format!(
            "the manifest declares {} as a path source, but its generated \
             pyproject.toml cannot be read. A manifest pointing at a shim that \
             does not exist would resolve to nothing at all",
            shim_dir.display()
        )
    })?;
    let parsed: toml::Value = toml::from_str(&text)
        .with_context(|| format!("parsing {} as a generated shim", file.display()))?;
    let rel = parsed
        .get("tool")
        .and_then(|t| t.get("setuptools"))
        .and_then(|s| s.get("package-dir"))
        .and_then(|p| p.get(""))
        .and_then(|v| v.as_str())
        .ok_or_else(|| {
            anyhow::anyhow!(
                "{} carries no [tool.setuptools.package-dir] \"\" entry, so the \
                 real tree it stands for cannot be recovered",
                file.display()
            )
        })?;
    let real = shim_dir.join(rel).canonicalize().with_context(|| {
        format!("resolving {rel} from {} to the real tree", shim_dir.display())
    })?;
    pathdiff_from_root(canonical_root, &real)
}

/// Derive one record per path source the named packs stand in for.
///
/// THE ONE AUTHORITY for "what is a path source of this workspace" is the
/// workspace manifest, read here and nowhere else in this module.
/// `workspace::parse_direct_source_pypi_names` was considered and does NOT
/// fit: it answers a different question (which pypi names are direct sources
/// of ANY of `url`/`path`/`git`) and returns names only, with no path value
/// and no way to tell a `path` from a `git`. Both halves are load-bearing
/// here, so this reads the `path` entries itself.
///
/// SELECTION, in full, because every step of it is a refusal somewhere:
///
/// 1. A source is a candidate only if some scope declares BOTH it and one of
///    the named packs. `unitree_sdk2py` lives in `feature.jetson`, which
///    declares no pack of ours, so it is not shimmed — the same source whose
///    misreading produced the `unitree-sdk2py` bare-registry-root refusal.
/// 2. A source resolving to the workspace root itself is skipped:
///    `imprint = { path = "." }` is declared beside both packs and a workspace
///    cannot be a shim of itself.
/// 3. A source already resolving INSIDE a named pack's shim directory is
///    already repointed; its real tree is recovered from the shim.
/// 4. One candidate pack wins outright. More than one is decided by
///    [`pack_builds_project`], and anything that does not leave exactly one
///    REFUSES naming every candidate.
/// 5. A source the manifest already points at ANOTHER pack's generated shim
///    belongs to that pack and is carried out in [`Derivation::elsewhere`],
///    never claimed and never silently dropped.
pub fn derive_records(
    packs: &[PathBuf],
    workspace_root: &Path,
    records_dir: &str,
    manifest_text: &str,
    dynamic: Option<&dyn DynamicDependencySource>,
    config_allows_generated_records: bool,
) -> Result<Derivation> {
    let canonical_root = workspace_root
        .canonicalize()
        .with_context(|| format!("canonicalizing {}", workspace_root.display()))?;

    // Canonical pack directory -> the argument that named it.
    let mut named_packs: Vec<(PathBuf, PathBuf)> = Vec::new();
    for pack_dir in packs {
        let canonical = pack_dir
            .canonicalize()
            .with_context(|| format!("canonicalizing pack {}", pack_dir.display()))?;
        named_packs.push((canonical, pack_dir.clone()));
    }

    // project -> (path as declared, declaring scopes, candidate packs)
    let mut candidates: BTreeMap<String, (String, Vec<String>, Vec<PathBuf>)> = BTreeMap::new();
    for scope in manifest_scopes(manifest_text)? {
        let scope_packs: Vec<PathBuf> = scope
            .conda_paths
            .iter()
            .filter_map(|p| resolve_under(&canonical_root, p))
            .filter_map(|resolved| {
                named_packs
                    .iter()
                    .find(|(canonical, _)| *canonical == resolved)
                    .map(|(_, named)| named.clone())
            })
            .collect();
        if scope_packs.is_empty() {
            continue;
        }
        for (raw_name, path) in &scope.pypi_paths {
            let project = normalize_dist_name(raw_name);
            if project.is_empty() {
                continue;
            }
            let Some(resolved) = resolve_under(&canonical_root, path) else {
                bail!(
                    "[feature.{}] declares `{raw_name} = {{ path = \"{path}\" }}` beside a \
                     path-source pack, but nothing is at that path. A source the lock \
                     will try to build and this transform cannot see is the silent slow \
                     path this refuses to leave in place.",
                    scope.name
                );
            };
            if resolved == canonical_root {
                continue; // `imprint = { path = "." }` — the workspace itself.
            }
            let slot = candidates.entry(project).or_insert_with(|| {
                (path.clone(), Vec::new(), Vec::new())
            });
            if slot.0 != *path {
                bail!(
                    "`{raw_name}` is declared with two different paths: \"{}\" and \
                     \"{path}\". One project is one tree; the effective manifest can \
                     repoint it at one shim only.",
                    slot.0
                );
            }
            slot.1.push(scope.name.clone());
            for pack in &scope_packs {
                if !slot.2.contains(pack) {
                    slot.2.push(pack.clone());
                }
            }
        }
    }

    let mut derived = Vec::new();
    let mut elsewhere = Vec::new();
    let mut metadata_rows: Vec<String> = Vec::new();
    let mut facts_rows: Vec<String> = Vec::new();
    let mut derived_records_to_write: Vec<(PathBuf, String)> = Vec::new();
    for (project, (declared_path, scopes, mut pack_candidates)) in candidates {
        if pack_candidates.len() > 1 {
            let mut builders = Vec::new();
            for pack in &pack_candidates {
                if pack_builds_project(pack, &project)? {
                    builders.push(pack.clone());
                }
            }
            if builders.len() != 1 {
                bail!(
                    "`{project}` is declared in [feature.{}] beside {} packs \
                     ({}), and {} of them build `{project}` \
                     ([package.build.config.retread-wheels]). Exactly one pack must \
                     stand in for one source: the effective manifest can point it at \
                     one shim only.",
                    scopes.join("], [feature."),
                    pack_candidates.len(),
                    pack_candidates
                        .iter()
                        .map(|p| p.display().to_string())
                        .collect::<Vec<_>>()
                        .join(", "),
                    builders.len()
                );
            }
            pack_candidates = builders;
        }
        let pack = pack_candidates.remove(0);
        let shim = pack.join(SHIMS_DIR).join(&project);

        // Already repointed? Then the declared path IS the shim and the real
        // tree is recovered from it.
        let declared = resolve_under(&canonical_root, &declared_path);
        let inside_shim = declared
            .as_ref()
            .zip(shim.canonicalize().ok())
            .is_some_and(|(d, s)| *d == s);
        // ANOTHER PACK'S SHIM. The manifest already points this source at a
        // generated `sources/<project>` that is not this pack's, so the pack
        // that stands in for it is that one, not this one. Deriving it here
        // would read a shim directory as if it were a source tree — a shim
        // states no version anywhere `tree_facts` looks — and would then write
        // a second, competing shim for one source. Carried out as a row.
        let declared_is_other_shim = !inside_shim
            && declared
                .as_ref()
                .and_then(|d| d.parent())
                .and_then(|p| p.file_name())
                .and_then(|s| s.to_str())
                == Some(SHIMS_DIR);
        if declared_is_other_shim {
            elsewhere.push(format!(
                "{project} (the manifest declares it at \"{declared_path}\", another \
                 pack's generated shim; {} does not stand in for it)",
                pack.display()
            ));
            continue;
        }
        let real_path = if inside_shim {
            real_tree_behind_shim(&shim, &canonical_root)?
        } else {
            declared_path.clone()
        };

        let tree = canonical_root.join(&real_path);
        let mut facts = tree_facts(&tree)
            .with_context(|| format!("reading the facts `{project}`'s tree states at {}", tree.display()))?;

        // METAGEN-1. The tree states its dependencies in exactly one of three
        // ways, and only the third costs anything.
        //
        //  1. a static `[project].dependencies` -- `imprint`, `unitree_sdk2py`.
        //     `tree_facts` never looked here, so a static editable's list was
        //     invisible to the derivation as well; read it, and never build.
        //  2. an `*.egg-info/PKG-INFO` -- what `tree_facts` already reads.
        //  3. NOWHERE. `pace_sim2real` declares `install_requires` as a python
        //     LIST built from a module-level name, which no text reader can
        //     honestly parse, so before this the derivation emitted
        //     `dependencies = []` SILENTLY and dropped `psutil` and `cmaes`.
        //     Ask the tree's own build backend, in an isolated environment.
        //
        // METAGEN-2 (N27-RETREAD-223). `static_dependencies` is ALSO the reader
        // that decides `dynamic`: it returns `None` when the tree's pyproject
        // lists `dependencies` in `[project].dynamic`, when it has no `[project]`
        // table, and when there is no pyproject at all — the three shapes in
        // which the ONLY honest producer is the tree's own build backend. It
        // returns `Some(vec![])` for an explicit `dependencies = []`, which IS a
        // statement of emptiness and must never be built for.
        let stated_statically = crate::derived_editable_metadata::static_dependencies(&tree)
            .with_context(|| {
                format!("reading `{project}`'s own [project] table at {}", tree.display())
            })?;
        let dependencies_are_dynamic = stated_statically.is_none();
        // Where the dependencies that get LOCKED came from, as one word, for the
        // decision row below: `stated` = the tree itself said them (PKG-INFO
        // `Requires-Dist` or a static `[project].dependencies`), `derived` = a
        // metadata build said them (this run's, or one written down in a
        // generated record), `absent` = nobody said them and `dependencies = []`
        // is about to be locked. Before METAGEN-2 the third case was
        // unobservable, which is what made the silence a defect rather than a
        // choice.
        let mut deps_source = if facts.dependencies.is_some() {
            "stated"
        } else {
            "absent"
        };
        if facts.dependencies.is_none()
            && let Some(stated) = stated_statically
        {
            facts.dependencies = Some((stated, tree.join("pyproject.toml")));
            deps_source = "stated";
        }
        // THE GENERATED RECORD IS THE RECORD OF TRUTH; THE STORE IS THE CACHE.
        // A record already on disk whose `source-hash` matches the tree's hash
        // TODAY states the derived dependencies, so nothing is built at all --
        // not even a store lookup. A record whose hash has MOVED is stale and
        // the run rederives it (auto) and rewrites it. A record with no
        // `source-hash` at all -- every hand-written one -- is left to the
        // confirm-or-refuse path below, exactly as before.
        let record_file = pack.join(records_dir).join(format!("{project}.toml"));
        let mut recorded: Option<PathSourceEntry> = None;
        let mut record_stale = false;
        if facts.dependencies.is_none() && record_file.is_file() {
            let text = std::fs::read_to_string(&record_file)
                .with_context(|| format!("reading {}", record_file.display()))?;
            let on_disk: PathSourceEntry = toml::from_str(&text)
                .with_context(|| format!("parsing {} as a path-source record", record_file.display()))?;
            if let Some(recorded_hash) = on_disk.source_hash.as_deref() {
                let current = crate::derived_editable_metadata::source_hash(&tree)
                    .with_context(|| {
                        format!("hashing `{project}`'s tree at {} to check {} for staleness", tree.display(), record_file.display())
                    })?;
                if recorded_hash == current {
                    facts.dependencies =
                        Some((on_disk.dependencies.clone(), record_file.clone()));
                    if facts.requires_python.is_none() {
                        facts.requires_python = on_disk.requires_python.clone().map(|value| TreeFact {
                            value,
                            source: record_file.clone(),
                        });
                    }
                    recorded = Some(on_disk);
                    // A generated record IS a derivation, written down. The row
                    // says `derived` and not `stated` so a reader can never
                    // mistake the record for the tree's own statement.
                    deps_source = "derived";
                } else {
                    record_stale = true;
                }
            }
        }
        if facts.dependencies.is_none()
            && let Some(source) = dynamic
        {
            if !config_allows_generated_records {
                bail!(
                    "`{project}`'s tree at {} states its dependencies nowhere, and \
                     {} declares `{}` = false -- so no generated record may be \
                     written here. Either allow the generated record, or produce \
                     it once by hand:\n  pixi-build-retread path-source-refresh \
                     --pack {} --workspace {} --project {project} --write\n\
                     Refusing rather than locking `dependencies = []`, which is \
                     the silent drop this capability exists to remove.",
                    tree.display(),
                    pack.display(),
                    crate::derived_editable_metadata::GENERATED_RECORDS_KEY,
                    pack.display(),
                    workspace_root.display()
                );
            }
            let derived = source.derive(&tree).with_context(|| {
                format!(
                    "`{project}` states its dependencies nowhere -- not in a \
                     [project] table, not in an *.egg-info/PKG-INFO, not in a \
                     generated record -- so they were derived from {}",
                    tree.display()
                )
            })?;
            metadata_rows.push(format!(
                "{} record={} reason={}",
                derived.row(&real_path),
                record_file.display(),
                if record_stale { "stale-record" } else { "no-record" }
            ));
            derived_records_to_write.push((record_file.clone(), derived.source_hash.clone()));
            deps_source = "derived";
            facts.dependencies = Some((derived.metadata.requires_dist.clone(), tree.clone()));
            // The same build states these two as well, and a tree that states
            // neither anywhere else would otherwise lose them.
            if facts.requires_python.is_none()
                && let Some(value) = derived.metadata.requires_python.clone()
            {
                facts.requires_python = Some(TreeFact {
                    value,
                    source: tree.clone(),
                });
            }
            if facts.version.is_none()
                && let Some(value) = derived.metadata.version.clone()
            {
                facts.version = Some(TreeFact {
                    value,
                    source: tree.clone(),
                });
            }
        }

        // THE DECISION, AS A ROW, FOR EVERY SOURCE — the reader METAGEN-2 owes.
        // `### EDITABLE METADATA DERIVED` prints only when a build ran, so the
        // two cases that lock `dependencies = []` printed NOTHING: the tree
        // whose PKG-INFO lists no `Requires-Dist` (arm C, ProtoMotions) and the
        // run with the deriver switched off (arm A-off). One row per source,
        // always, names which producer supplied the dependencies and the two
        // facts the choice was made on, so a relock's evidence packet can be
        // read for `deps=absent` instead of inferring it from a silence.
        facts_rows.push(format!(
            "### PATH SOURCE FACTS name={project} deps={deps_source} \
             requires_dist={} dynamic={}",
            facts.requires_dist,
            if dependencies_are_dynamic { "yes" } else { "no" }
        ));

        let seed = PathSourceEntry {
            path: real_path.clone(),
            ..PathSourceEntry::default()
        };
        let mut entry = record_from_tree(&project, &seed, &facts).with_context(|| {
            format!(
                "deriving the path-source record for `{project}` from {}",
                tree.display()
            )
        })?;
        // Carry the hash forward from whichever half supplied the dependencies:
        // the record we just read back and accepted, or the build we just ran.
        if let Some(recorded) = recorded.as_ref() {
            entry.source_hash = recorded.source_hash.clone();
            entry.packages_include = recorded.packages_include.clone();
        }

        // A record file on disk may CONFIRM and may never be required.
        let file = record_file;
        let mut confirmed = false;
        // THE GENERATED WRITE. When this run DERIVED the dependencies, the
        // record on disk is absent or stale by construction, so it is written
        // rather than confirmed -- the file is the record of truth and a
        // derivation nobody wrote down is a fact the next run has to pay for
        // again. It goes through `write_under_pack`, so a records directory
        // outside the pack is a refusal and not a stray write.
        if let Some((_, hash)) = derived_records_to_write
            .iter()
            .find(|(target, _)| target == &file)
        {
            entry.source_hash = Some(hash.clone());
            let text = render_record(&project, &entry);
            // The containment check runs on the DIRECTORY first, so a records
            // directory outside the pack is refused before it is created.
            let Some(parent) = file.parent() else {
                bail!("{}: a record file with no parent directory", file.display());
            };
            write_under_pack(&pack, parent, None)?;
            std::fs::create_dir_all(parent)
                .with_context(|| format!("creating {}", parent.display()))?;
            write_under_pack(&pack, &file, Some(text.as_str()))?;
            metadata_rows.push(format!("### EDITABLE METADATA RECORD written={}", file.display()));
        } else if file.is_file() {
            let text = std::fs::read_to_string(&file)
                .with_context(|| format!("reading {}", file.display()))?;
            let on_disk: PathSourceEntry = toml::from_str(&text)
                .with_context(|| format!("parsing {} as a path-source record", file.display()))?;
            let mut want = entry.clone();
            // `packages-include` is a fact about the tree's LAYOUT that no
            // reader states, so a record is allowed to be the only statement
            // of it and carrying it forward is not a disagreement.
            want.packages_include = on_disk.packages_include.clone();
            // Nor is a `source-hash` on a record whose dependencies this run
            // read from a different producer: the hash describes how the record
            // was made, not what the tree says today.
            want.source_hash = on_disk.source_hash.clone();
            if on_disk != want {
                bail!(
                    "{} disagrees with the tree it describes. The record says\n  \
                     {on_disk:?}\nand {} states\n  {want:?}\nThe derivation is what \
                     gets locked; a record may only confirm it. Either delete the \
                     record or run `path-source-refresh --pack {} --workspace {} \
                     --project {project} --write`.",
                    file.display(),
                    tree.display(),
                    pack.display(),
                    workspace_root.display()
                );
            }
            confirmed = true;
        }

        derived.push(DerivedRecord {
            record: PathSourceRecord {
                project,
                file,
                entry,
            },
            pack,
            confirmed,
            shim,
        });
    }
    Ok(Derivation {
        records: derived,
        elsewhere,
        metadata_rows,
        facts_rows,
    })
}
/// The canonical manifest, transformed. `text` is what gets locked.
#[derive(Debug, Clone)]
pub struct EffectiveManifest {
    pub text: String,
    pub rewrites: Vec<ShimRewrite>,
    /// The records the transform DERIVED, in project order. Present so the
    /// caller can print where each one came from: a derivation nobody can read
    /// back is the same defect as a record nobody wrote.
    pub derived: Vec<DerivedRecord>,
    /// METAGEN-2's `### PATH SOURCE FACTS` rows then METAGEN-1's
    /// `### EDITABLE METADATA DERIVED` rows, in project order.
    pub metadata_rows: Vec<String>,
}

impl EffectiveManifest {
    /// Every evidence row, in record order.
    pub fn rows(&self) -> Vec<String> {
        self.rewrites.iter().map(ShimRewrite::row).collect()
    }

    /// One row per derived record, in project order.
    pub fn derivation_rows(&self) -> Vec<String> {
        self.derived.iter().map(DerivedRecord::row).collect()
    }
}

/// Rewrite every declared path source in `manifest_text` to the pack shim that
/// stands in for it.
///
/// A pure function of (manifest text, workspace layout, the trees' own
/// metadata): the same inputs give the same bytes, and running it on its own
/// output changes nothing. It writes nothing at all.
///
/// The records are DERIVED — see [`derive_records`]. Nothing has to exist
/// under `<pack>/<records_dir>/` for this to work, and what does exist there
/// may only confirm the derivation.
///
/// It REFUSES rather than falling back to the slow path, in every case where
/// the fast path would silently not happen:
///
/// * a `--pack` argument that is not a pack directory (missing, or holding no
///   `pixi.toml`) — a missing pack is the one failure that would otherwise
///   look exactly like success;
/// * a named pack that stands in for NO declared path source — a listed pack
///   with nothing to do is the law-2 defect this capability exists to avoid,
///   and it is the shape a stale `--pack` argument takes;
/// * a record file on disk that disagrees with the tree it describes;
/// * a derived source that the manifest declares neither at its real path nor
///   at its shim — repointing nothing would quietly leave a 1 800 s metadata
///   build in place.
pub fn plan_effective_manifest(
    packs: &[PathBuf],
    workspace_root: &Path,
    records_dir: &str,
    manifest_text: &str,
    dynamic: Option<&dyn DynamicDependencySource>,
    generated_records: bool,
) -> Result<EffectiveManifest> {
    if packs.is_empty() {
        bail!("no pack directory was given: there is nothing to generate shims from");
    }
    let canonical_root = workspace_root
        .canonicalize()
        .with_context(|| format!("canonicalizing {}", workspace_root.display()))?;

    for pack_dir in packs {
        if !pack_dir.join("pixi.toml").is_file() {
            bail!(
                "{} is not a pack directory: it holds no pixi.toml. Refusing to \
                 generate an effective manifest from a pack that is missing — a \
                 silent fall back to the original path sources is the slow lock \
                 this transform exists to remove.",
                pack_dir.display()
            );
        }
    }

    let derivation = derive_records(packs, workspace_root, records_dir, manifest_text, dynamic, generated_records)?;
    // The verb is given EVERY pack, so a source it declined to claim was
    // declared at the shim of a pack nobody named. Repointing nothing and
    // saying nothing is the silent miss; refusing names both halves.
    if !derivation.elsewhere.is_empty() {
        bail!(
            "the workspace manifest points {} at a generated shim of a pack that \
             was not named on this command line. Either name that pack with \
             --pack or repoint the source at its real tree: {}",
            derivation.elsewhere.len(),
            derivation.elsewhere.join("; ")
        );
    }
    let derived = derivation.records;
    // METAGEN-2: facts rows first, then the build rows — one stream, one order,
    // whichever caller prints it.
    let mut metadata_rows = derivation.facts_rows;
    metadata_rows.extend(derivation.metadata_rows);

    // A named pack that stands in for nothing is a gate with no producer: the
    // argument list and the manifest disagree and one of them is stale.
    for pack_dir in packs {
        if !derived.iter().any(|d| &d.pack == pack_dir) {
            bail!(
                "{} was named as a source of path-source shims, but no \
                 `[pypi-dependencies]` entry declaring a `path` appears in any \
                 manifest scope that also declares this pack. There is nothing for \
                 it to stand in for. Either declare the source beside the pack or \
                 drop the pack from the argument list.",
                pack_dir.display()
            );
        }
    }

    let mut text = manifest_text.to_string();
    let mut rewrites: Vec<ShimRewrite> = Vec::new();

    for record in &derived {
        let to = pathdiff_from_root(&canonical_root, &record.shim)?;
        let from = record.record.entry.path.trim_end_matches('/').to_string();
        if from.is_empty() {
            bail!("{}: `path` is empty", record.record.file.display());
        }
        let (next, lines) = repoint_path_entries(&text, &from, &to);
        let already = lines == 0 && declares_path(&text, &to);
        if lines == 0 && !already {
            bail!(
                "`{}` was derived with path = \"{from}\", but no `[pypi-dependencies]` \
                 entry in the workspace manifest declares it and the shim \
                 \"{to}\" is not declared either. Repointing nothing would leave the \
                 PEP 517 metadata build in place and the lock slow, so this refuses \
                 instead.",
                record.record.project
            );
        }
        text = next;
        rewrites.push(ShimRewrite {
            project: record.record.project.clone(),
            from,
            to,
            pack: record.pack.clone(),
            lines,
            already,
        });
    }
    Ok(EffectiveManifest {
        text,
        rewrites,
        derived,
        metadata_rows,
    })
}

/// [`plan_effective_manifest`] plus the shim materialisation, in the one order
/// that works: the shims are generated against the EFFECTIVE text, because
/// that is the manifest whose `path =` entries they have to match.
///
/// This is the whole capability behind one name, for the same reason
/// [`materialize_declared_path_sources`] is: a guard that called only the
/// planner would stay green if the shim writer were unwired.
pub fn generate_effective_manifest(
    packs: &[PathBuf],
    workspace_root: &Path,
    records_dir: &str,
    manifest_text: &str,
    dynamic: Option<&dyn DynamicDependencySource>,
    generated_records: bool,
) -> Result<(EffectiveManifest, Vec<PathSourceOutcome>)> {
    let effective = plan_effective_manifest(packs, workspace_root, records_dir, manifest_text, dynamic, generated_records)?;
    let mut outcomes = Vec::new();
    for pack_dir in packs {
        // THE DERIVED RECORDS, not the files on disk. Reloading from disk here
        // would reintroduce the whole defect one level down: production has no
        // files there, so the planner would repoint the manifest at shims that
        // were never written and every entry would resolve to nothing.
        let mine: Vec<PathSourceRecord> = effective
            .derived
            .iter()
            .filter(|d| &d.pack == pack_dir)
            .map(|d| d.record.clone())
            .collect();
        outcomes.extend(generate_shims_from(
            pack_dir,
            workspace_root,
            None,
            &effective.text,
            &mine,
        )?);
    }
    Ok((effective, outcomes))
}

/// The transform AND its opt-out behind one name.
///
/// `shims = false` returns the canonical bytes verbatim and no rewrites — the
/// `--no-pack-shims` control. It lives here rather than as a branch in the CLI
/// so the opt-out has a guard that drives the same code production does; an
/// opt-out only the CLI knows about is an untested claim.
pub fn effective_manifest_text(
    packs: &[PathBuf],
    workspace_root: &Path,
    records_dir: &str,
    manifest_text: &str,
    shims: bool,
    dynamic: Option<&dyn DynamicDependencySource>,
    generated_records: bool,
) -> Result<(
    String,
    Vec<ShimRewrite>,
    Vec<PathSourceOutcome>,
    Vec<DerivedRecord>,
    Vec<String>,
)> {
    if !shims {
        return Ok((
            manifest_text.to_string(),
            Vec::new(),
            Vec::new(),
            Vec::new(),
            Vec::new(),
        ));
    }
    let (effective, outcomes) =
        generate_effective_manifest(packs, workspace_root, records_dir, manifest_text, dynamic, generated_records)?;
    Ok((
        effective.text,
        effective.rewrites,
        outcomes,
        effective.derived,
        effective.metadata_rows,
    ))
}

/// Replace `path = "<from>"` with `path = "<to>"` on every manifest line that
/// carries both, and report how many lines moved.
///
/// Line-wise and substring-exact on purpose. The manifest is hand-maintained
/// TOML with comments and section ordering that reviewers read; a parse-and-
/// re-emit round trip would rewrite the whole file and make the diff
/// unreviewable. The measured target is a four-line diff, and this produces
/// exactly those four lines and not one byte more. A prose mention of the same
/// path in a comment does not match: the needle carries its quotes and the
/// line must also carry the `path` key.
fn repoint_path_entries(manifest_text: &str, from: &str, to: &str) -> (String, usize) {
    let needles = [
        (format!("\"{from}\""), format!("\"{to}\"")),
        (format!("'{from}'"), format!("'{to}'")),
    ];
    let mut moved = 0usize;
    let mut out = String::with_capacity(manifest_text.len() + 64);
    for (index, line) in manifest_text.split_inclusive('\n').enumerate() {
        let _ = index;
        let mut rewritten = line.to_string();
        if line.contains("path") {
            for (needle, replacement) in &needles {
                if rewritten.contains(needle.as_str()) {
                    rewritten = rewritten.replace(needle.as_str(), replacement);
                    moved += 1;
                }
            }
        }
        out.push_str(&rewritten);
    }
    (out, moved)
}

/// Does any `path =` entry in the manifest already declare `rel`?
fn declares_path(manifest_text: &str, rel: &str) -> bool {
    manifest_text.lines().any(|line| {
        line.contains("path")
            && (line.contains(&format!("\"{rel}\"")) || line.contains(&format!("'{rel}'")))
    })
}

/// The declared sources, for the backend's own log line.
pub fn declared_summary(records: &[PathSourceRecord]) -> String {
    records
        .iter()
        .map(|r| format!("{}@{}", r.project, r.entry.path))
        .collect::<Vec<_>>()
        .join(", ")
}

