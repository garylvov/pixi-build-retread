/// One fact the real tree states, and the file that states it. Both are in
/// every refusal message: "your record says X, `<file>` says Y".
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TreeFact {
    pub value: String,
    pub source: PathBuf,
}

/// Everything the real tree says about itself, from every place it says it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TreeFacts {
    pub name: Option<TreeFact>,
    pub version: Option<TreeFact>,
    pub requires_python: Option<TreeFact>,
    /// `None` = the tree states nothing about its dependencies anywhere, so
    /// there is nothing to check and nothing to lock without deriving it.
    /// `Some(vec![])` = it states that it has none, which ONLY a static
    /// `[project].dependencies = []` says: see `requires_dist`.
    pub dependencies: Option<(Vec<String>, PathBuf)>,
    /// How many `Requires-Dist` headers the tree's own `*.egg-info/PKG-INFO`
    /// states — 0 both when there is no egg-info and when the egg-info lists
    /// none. METAGEN-2 (N27-RETREAD-223): the two are told apart by
    /// `dependencies`, and NEITHER is a statement that the tree has none.
    /// Carried so the decision row can print the count it was decided on.
    pub requires_dist: usize,
}

/// Read the tree's own statements of the four fields.
///
/// Three readers, in decreasing authority:
///  1. `*.egg-info/PKG-INFO` — written by the tree's own build backend, so it
///     is exactly what a metadata build would produce. All four fields.
///  2. `config/extension.toml` `[package] version` — what `pace-sim2real`'s
///     `setup.py` `toml.load`s at build time.
///  3. `setup.py` literal `version=` / `python_requires=` — what
///     `ProtoMotions` states in source.
///
/// A later reader never overrides an earlier one; it only fills a gap. A
/// missing tree is not an error here (the caller has already refused).
pub fn tree_facts(dir: &Path) -> Result<TreeFacts> {
    let mut facts = TreeFacts::default();

    if let Some(pkg_info) = find_pkg_info(dir)? {
        let text = std::fs::read_to_string(&pkg_info)
            .with_context(|| format!("reading {}", pkg_info.display()))?;
        let mut requires_dist = Vec::new();
        let mut saw_headers = false;
        for line in text.lines() {
            if line.is_empty() {
                break; // headers end at the first blank line
            }
            let Some((key, value)) = line.split_once(':') else {
                continue;
            };
            saw_headers = true;
            let value = value.trim().to_string();
            let fact = TreeFact {
                value: value.clone(),
                source: pkg_info.clone(),
            };
            match key.to_ascii_lowercase().as_str() {
                "name" => {
                    facts.name.get_or_insert(fact);
                }
                "version" => {
                    facts.version.get_or_insert(fact);
                }
                "requires-python" => {
                    facts.requires_python.get_or_insert(fact);
                }
                "requires-dist" => requires_dist.push(value),
                _ => {}
            }
        }
        facts.requires_dist = requires_dist.len();
        // METAGEN-2 (N27-RETREAD-223). "The tree states its dependencies" means
        // the metadata ACTUALLY STATES THEM. `saw_headers` was the predicate
        // here, and it is true for any PKG-INFO carrying any header at all: a
        // `Metadata-Version`/`Name`/`Version`/`Requires-Python` block with ZERO
        // `Requires-Dist` lines was therefore read as the statement "this tree
        // has no dependencies", the isolated build was skipped, and the shim
        // locked `dependencies = []` with nothing in any log saying so. That is
        // ProtoMotions' live PKG-INFO shape, measured: `grep -c '^Requires-Dist'`
        // = 0 with `Metadata-Version: 2.4`.
        //
        // An empty `Requires-Dist` list in core metadata is not a statement of
        // emptiness — for a tree whose `setup.py` COMPUTES `install_requires` it
        // is the absence of one, and the egg-info a stale checkout carries says
        // nothing about the tree as it stands today. So the PKG-INFO states the
        // dependencies only when it LISTS them; the headers still state
        // `name`/`version`/`requires-python` above, which is why those fields
        // are read unconditionally and this one is not. A tree that really has
        // none says so where it cannot be confused with silence: a static
        // `[project].dependencies = []`, which `static_dependencies` reads and
        // `derive_records` consults next.
        if saw_headers && !requires_dist.is_empty() {
            facts.dependencies = Some((requires_dist, pkg_info));
        }
    }

    // pace-sim2real: setup.py reads config/extension.toml at build time.
    let ext = dir.join("config").join("extension.toml");
    if facts.version.is_none() && ext.is_file() {
        let text = std::fs::read_to_string(&ext)
            .with_context(|| format!("reading {}", ext.display()))?;
        if let Ok(value) = toml::from_str::<toml::Value>(&text)
            && let Some(v) = value
                .get("package")
                .and_then(|p| p.get("version"))
                .and_then(|v| v.as_str())
        {
            facts.version = Some(TreeFact {
                value: v.to_string(),
                source: ext,
            });
        }
    }

    // ProtoMotions: literal keywords in setup.py.
    let setup_py = dir.join("setup.py");
    if setup_py.is_file() {
        let text = std::fs::read_to_string(&setup_py)
            .with_context(|| format!("reading {}", setup_py.display()))?;
        if facts.version.is_none()
            && let Some(v) = scan_setup_kwarg(&text, "version")
        {
            facts.version = Some(TreeFact {
                value: v,
                source: setup_py.clone(),
            });
        }
        if facts.requires_python.is_none()
            && let Some(v) = scan_setup_kwarg(&text, "python_requires")
        {
            facts.requires_python = Some(TreeFact {
                value: v,
                source: setup_py.clone(),
            });
        }
        if facts.name.is_none()
            && let Some(v) = scan_setup_kwarg(&text, "name")
        {
            facts.name = Some(TreeFact {
                value: v,
                source: setup_py,
            });
        }
    }

    Ok(facts)
}

/// `version="3.1"` / `python_requires='>=3.8'` — a literal keyword argument
/// with a quoted string value. Deliberately only literals: a computed value
/// is not a fact this can read, and guessing one would be worse than the
/// PKG-INFO it falls back to.
fn scan_setup_kwarg(text: &str, kwarg: &str) -> Option<String> {
    for line in text.lines() {
        let trimmed = line.trim_start();
        let Some(rest) = trimmed.strip_prefix(kwarg) else {
            continue;
        };
        let rest = rest.trim_start();
        let Some(rest) = rest.strip_prefix('=') else {
            continue;
        };
        let rest = rest.trim_start();
        let Some(quote) = rest.chars().next() else {
            continue;
        };
        if quote != '"' && quote != '\'' {
            continue;
        }
        let body = &rest[1..];
        if let Some(end) = body.find(quote) {
            return Some(body[..end].to_string());
        }
    }
    None
}

/// Compare the record against the tree and refuse on any disagreement,
/// naming the record file (what to edit), the field, and both values with
/// the tree file that states the other one.
pub fn check_drift(record: &PathSourceRecord, facts: &TreeFacts) -> Result<()> {
    let file = record.file.display();
    if let Some(fact) = &facts.name
        && normalize_dist_name(&fact.value) != normalize_dist_name(&record.project)
    {
        bail!(
            "path-source record drift: {file} is keyed `{}`, but {} says the \
             project is named `{}`. Edit {file} (or rename it), or run \
             `pixi-build-retread path-source-refresh --write`.",
            record.project,
            fact.source.display(),
            fact.value,
        );
    }
    if let Some(fact) = &facts.version
        && fact.value != record.entry.version
    {
        bail!(
            "path-source record drift: {file} declares `version = \"{}\"`, but \
             {} says `{}`. The record is stale — the lock would claim a version \
             the installed tree does not have. Edit the `version` field of \
             {file}, or run `pixi-build-retread path-source-refresh --write` and \
             review the diff.",
            record.entry.version,
            fact.source.display(),
            fact.value,
        );
    }
    if let Some(fact) = &facts.requires_python
        && Some(fact.value.as_str()) != record.entry.requires_python.as_deref()
    {
        bail!(
            "path-source record drift: {file} declares `requires-python = {:?}`, \
             but {} says `{}`. Edit the `requires-python` field of {file}, or \
             run `pixi-build-retread path-source-refresh --write`.",
            record.entry.requires_python,
            fact.source.display(),
            fact.value,
        );
    }
    if let Some((deps, source)) = &facts.dependencies
        && deps != &record.entry.dependencies
    {
        bail!(
            "path-source record drift: {file} declares `dependencies = {:?}`, but \
             {} lists {:?}. A dependency the record omits is a dependency the \
             resolver will never see. Edit the `dependencies` field of {file}, or \
             run `pixi-build-retread path-source-refresh --write`.",
            record.entry.dependencies,
            source.display(),
            deps,
        );
    }
    Ok(())
}

/// Build the record a tree's own facts imply — the `--write` half of
/// `path-source-refresh`. Everything the tree does not state is carried over
/// from the current record, so a refresh never invents and never drops.
pub fn record_from_tree(
    project: &str,
    current: &PathSourceEntry,
    facts: &TreeFacts,
) -> Result<PathSourceEntry> {
    let Some(version) = facts.version.as_ref().map(|f| f.value.clone()) else {
        bail!(
            "cannot refresh `{project}` from the tree: nothing in it states a \
             version (no *.egg-info/PKG-INFO, no config/extension.toml \
             [package] version, no literal `version=` in setup.py). Edit the \
             record by hand."
        );
    };
    Ok(PathSourceEntry {
        path: current.path.clone(),
        version,
        // METAGEN-1: a refresh FROM THE TREE carries the record's hash
        // forward. `path-source-refresh --write` re-states the tree's facts; it
        // does not run an isolated build, so it has no new hash to state and
        // dropping the old one would make a derived record look hand-written.
        source_hash: current.source_hash.clone(),
        requires_python: facts
            .requires_python
            .as_ref()
            .map(|f| f.value.clone())
            .or_else(|| current.requires_python.clone()),
        dependencies: facts
            .dependencies
            .as_ref()
            .map(|(d, _)| d.clone())
            .unwrap_or_else(|| current.dependencies.clone()),
        packages_include: current.packages_include.clone(),
    })
}

